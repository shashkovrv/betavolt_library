def get_doi_url(doi_str):
    if not doi_str:
        return "https://doi.org/"
    doi_str = doi_str.strip()
    if doi_str.startswith("10."):
        return f"https://doi.org/{doi_str}"
    elif doi_str.startswith("http"):
        return doi_str
    elif "ISBN 5-02-024958-8" in doi_str:
        return "https://www.elibrary.ru/item.asp?id=19830508"
    elif "621.039" in doi_str:
        return "https://www.elibrary.ru/item.asp?id=30751980"
    elif "621.383" in doi_str:
        return "https://www.elibrary.ru/item.asp?id=18244793"
    elif "621.315" in doi_str:
        return "https://www.elibrary.ru/item.asp?id=23846614"
    elif "978-0-471-41526-8" in doi_str:
        return "https://www.wiley.com/en-us/Introduction+to+Solid+State+Physics%2C+8th+Edition-p-9780471415268"
    return f"https://doi.org/{doi_str}"

